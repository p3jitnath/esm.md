.Lphotosynthesis_C4_candidate:
    ldr w9,[sp,#S_C4_IROOT]
    ldr w10,[sp,#S_C4_NROOT]
    cmp w9,w10
    b.ge .Lphotosynthesis_C4_next_pair
    C4_ADDRESS x10,C4_ROOT0
    ldr d0,[x10,w9,uxtw #3]
    PUT d0,C4_W
    CALC fsub,C4_NET,C4_W,RD_LEAF
    GET d0,C4_W
    fcmp d0,#0.0
    b.lt .Lphotosynthesis_C4_next_root
    GET d1,X1
    fcmp d0,d1
    b.ge .Lphotosynthesis_C4_next_root
    CALC fdiv,T0,C4_NET,GB
    CALC fsub,C4_CS,CO2,T0
    GET d0,C4_CS
    GET d1,C4_STAR
    fcmp d0,d1
    b.le .Lphotosynthesis_C4_next_root
    CALC fsub,T0,C4_CS,C4_STAR
    CALC fdiv,T0,C4_W,T0
    CALC fmul,T0,T0,FVPD
    CALC fadd,C4_GS,G0,T0
    GET d0,C4_GS
    fcmp d0,#0.0
    b.le .Lphotosynthesis_C4_next_root
    CALC fdiv,T0,C4_NET,C4_GS
    CALC fsub,C4_CI,C4_CS,T0
    GET d0,C4_CI
    fcmp d0,#0.0
    b.le .Lphotosynthesis_C4_next_root
    CALC fmul,T0,C4_ALPHA,C4_NET
    CALC fmul,T1,C4_DIFF,C4_GBS
    CALC fdiv,T0,T0,T1
    CALC fadd,C4_O,T0,C4_OI
    CALC fmul,T0,X2,C4_O
    CALC fadd,T0,T0,C4_X3
