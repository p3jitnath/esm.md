    CALC fmul,T1,C4_DIFF,C4_GBS
    CALC fdiv,T0,T0,T1
    CALC fadd,C4_O,T0,C4_OI
    CALC fmul,T0,X2,C4_O
    CALC fadd,T0,T0,C4_X3
    CALC fmul,T0,GROSS,T0
    CALC fmul,T1,LOW_GAMMA,C4_O
    CALC fmul,T1,T1,X1
    CALC fadd,T0,T0,T1
    CALC fsub,T1,X1,GROSS
    CALC fdiv,CC,T0,T1
    CALC fsub,T0,C4_PB,ASSIM_LEAF
    CALC fsub,T0,T0,C4_RM
    CALC fdiv,T0,T0,C4_GBS
    CALC fsub,T0,CC,T0
    CALC fdiv,CI,T0,C4_PA
    CALC fdiv,T0,ASSIM_LEAF,GB
    CALC fsub,T0,CO2,T0
    CALC fsub,T0,T0,C4_STAR
    CALC fdiv,T0,GROSS,T0
    CALC fmul,T0,T0,FVPD
    CALC fadd,GS_LEAF,G0,T0
    b .Lphotosynthesis_leaf_ready
