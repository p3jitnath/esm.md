    ldr w9,[sp,#S_C4_PAIR]
    cmp w9,#1
    b.eq .Lphotosynthesis_C4_pump_enzyme
    cmp w9,#4
    b.eq .Lphotosynthesis_C4_pump_enzyme
    COPY C4_PA,ONE
    COPY C4_PB,C4_VPJ
    b .Lphotosynthesis_C4_coefficients
