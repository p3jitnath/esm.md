    CALC fadd,T0,T0,T1
    CALC fsub,T1,X1,C4_W
    CALC fdiv,C4_CC,T0,T1
    GET d0,C4_CC
    fcmp d0,#0.0
    b.le .Lphotosynthesis_C4_next_root
    CALC fmul,T0,LOW_GAMMA,C4_O
    CALC fsub,T0,C4_CC,T0
    CALC fmul,T0,VC_LEAF,T0
    CALC fdiv,T1,C4_O,KMO
    CALC fadd,T1,ONE,T1
    CALC fmul,T1,KMC,T1
    CALC fadd,T1,C4_CC,T1
    CALC fdiv,C4_RC,T0,T1
    CALC fmul,T0,LOW_GAMMA,C4_O
    CALC fsub,T0,C4_CC,T0
    CALC fmul,T0,C4_XJ,T0
    CALC fmul,T1,C4_X2J,C4_O
    CALC fadd,T1,C4_CC,T1
    CALC fdiv,C4_RJ,T0,T1
    ldr w9,[sp,#S_C4_PAIR]
    cmp w9,#1
    b.eq .Lphotosynthesis_C4_require_rub_enzyme
    cmp w9,#3
    b.eq .Lphotosynthesis_C4_require_rub_enzyme
    GET d0,C4_RJ
    GET d1,C4_RC
    fcmp d0,d1
    b.gt .Lphotosynthesis_C4_next_root
    b .Lphotosynthesis_C4_check_pump
.Lphotosynthesis_C4_require_rub_enzyme:
    GET d0,C4_RC
    GET d1,C4_RJ
    fcmp d0,d1
    b.gt .Lphotosynthesis_C4_next_root
.Lphotosynthesis_C4_check_pump:
    CALC fmul,C4_VP,C4_KP,C4_CI
    ldr w9,[sp,#S_C4_PAIR]
    cmp w9,#1
    b.eq .Lphotosynthesis_C4_require_pump_enzyme
    cmp w9,#4
    b.eq .Lphotosynthesis_C4_require_pump_enzyme
    GET d0,C4_VPJ
    GET d1,C4_VP
    fcmp d0,d1
    b.gt .Lphotosynthesis_C4_next_root
    b .Lphotosynthesis_C4_select
.Lphotosynthesis_C4_require_pump_enzyme:
    GET d0,C4_VP
    GET d1,C4_VPJ
    fcmp d0,d1
    b.gt .Lphotosynthesis_C4_next_root
.Lphotosynthesis_C4_select:
    ldr w9,[sp,#S_C4_FOUND]
    cbz w9,.Lphotosynthesis_C4_save
    GET d0,C4_NET
    GET d1,SELECTED
    fcmp d0,d1
    b.ge .Lphotosynthesis_C4_next_root
.Lphotosynthesis_C4_save:
    COPY C4_SAVED_W,C4_W
    COPY SELECTED,C4_NET
    COPY C4_SAVED_PA,C4_PA
    COPY C4_SAVED_PB,C4_PB
    COPY C4_SAVED_X1,X1
    COPY C4_SAVED_X2,X2
    COPY C4_SAVED_X3,C4_X3
    ldr w9,[sp,#S_C4_PAIR]
    str w9,[sp,#S_C4_SELECTED_PAIR]
    mov w9,#1
    str w9,[sp,#S_C4_FOUND]
.Lphotosynthesis_C4_next_root:
    ldr w9,[sp,#S_C4_IROOT]
    add w9,w9,#1
    str w9,[sp,#S_C4_IROOT]
    b .Lphotosynthesis_C4_candidate
.Lphotosynthesis_C4_next_pair:
    ldr w9,[sp,#S_C4_PAIR]
    add w9,w9,#1
    str w9,[sp,#S_C4_PAIR]
    cmp w9,#4
    b.le .Lphotosynthesis_C4_pair
    ldr w9,[sp,#S_C4_FOUND]
    cbz w9,.Lphotosynthesis_reject
    COPY C4_PA,C4_SAVED_PA
    COPY C4_PB,C4_SAVED_PB
    COPY X1,C4_SAVED_X1
    COPY X2,C4_SAVED_X2
    COPY C4_X3,C4_SAVED_X3
    COPY GROSS,C4_SAVED_W
    COPY ASSIM_LEAF,SELECTED
