!! their admitted inputs and matching allocated profiles. Only the fields
!! documented by the four children change. No allocation occurs here.
  subroutine initialize_aerosol_distribution_parameter_fields(eta, shortwave, aerosol, radiation)
    real(real64), intent(in) :: eta(:)
