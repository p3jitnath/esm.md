!> Set five dimensionless MACC aerosol profiles from live scale heights.
!! MACC identifies the aerosol data family used by these profiles. eta(:)
!! has the same admitted shape and bounds as in the legacy child. The
!! five RAESH scale heights in radiation are positive finite metres.
!! Only the five allocated CVDAESS, CVDAEDU, CVDAEOM, CVDAEBC and CVDAESU
!! components change. All five divisions occur before the top-zero branch.
  subroutine initialize_macc_aerosol_vertical_profiles(eta, radiation)
    real(real64), intent(in) :: eta(:)
    type(terad), intent(inout) :: radiation
    real(real64) :: exponent(5)
    integer :: level, first_level, levels
    integer(int64) :: top_bits

    levels = size(eta) - 1
    exponent(1) = transfer(int(z'40C0790000000000', int64), 0.0_real64)/radiation%raeshss
    exponent(1) = max(exponent(1), 1.0_real64)
    exponent(2) = transfer(int(z'40C0790000000000', int64), 0.0_real64)/radiation%raeshdu
    exponent(2) = max(exponent(2), 1.0_real64)
    exponent(3) = transfer(int(z'40C0790000000000', int64), 0.0_real64)/radiation%raeshom
    exponent(3) = max(exponent(3), 1.0_real64)
    exponent(4) = transfer(int(z'40C0790000000000', int64), 0.0_real64)/radiation%raeshbc
    exponent(4) = max(exponent(4), 1.0_real64)
    exponent(5) = transfer(int(z'40C0790000000000', int64), 0.0_real64)/radiation%raeshsu
    exponent(5) = max(exponent(5), 1.0_real64)
    first_level = 1
    top_bits = transfer(eta(1), 0_int64)
    if (iand(top_bits, int(z'7FFFFFFFFFFFFFFF', int64)) == 0_int64) then
      radiation%cvdaess(1) = 0.0_real64
      radiation%cvdaedu(1) = 0.0_real64
      radiation%cvdaeom(1) = 0.0_real64
      radiation%cvdaebc(1) = 0.0_real64
      radiation%cvdaesu(1) = 0.0_real64
      first_level = 2
    end if
    do level = first_level, levels + 1
      radiation%cvdaess(level) = public_c_pow(eta(level), exponent(1))
      radiation%cvdaedu(level) = public_c_pow(eta(level), exponent(2))
      radiation%cvdaeom(level) = public_c_pow(eta(level), exponent(3))
      radiation%cvdaebc(level) = public_c_pow(eta(level), exponent(4))
      radiation%cvdaesu(level) = public_c_pow(eta(level), exponent(5))
    end do
  end subroutine initialize_macc_aerosol_vertical_profiles

!> Set all aerosol distribution fields in the complete source call order.
