!> Complete owned longwave pressure, temperature, gas and minor-factor preparation.
!! Inputs use hPa, K and molecular columns per cm2. Output molecular amounts
!! use the retained scale of 1e20 molecules/cm2. Reference tables are readonly.
!! Scientific source attribution: ECMWF and AER RRTM, RRTM_SETCOEF_140GP.
module native_longwave_coefficient_preparation
  use iso_fortran_env, only: JPIM => int32, JPRB => real64
  use yomdimv, only: TDIMV
  use longwave_reference_parameter_fields_mod, only: longwave_reference_parameter_record
  implicit none
  private
  public :: rrtm_setcoef_140gp
contains
  !> Update all forty declared output owners in native column-first arrays.
  !! Inputs and outputs are disjoint. Unused upper ratio/self metadata and
  !! inactive level tails retain their incoming bytes. The caller admits the
  !! retained finite physical domain and establishes the FP64 mode once.
  subroutine rrtm_setcoef_140gp(owned_reference,YDDIMV,KIDIA,KFDIA,KLEV,P_COLDRY,P_WBROAD,P_WKL, P_FAC00,P_FAC01,P_FAC10,P_FAC11,P_FORFAC,P_FORFRAC,K_INDFOR,K_JP,K_JT,K_JT1, P_COLH2O,P_COLCO2,P_COLO3,P_COLN2O,P_COLCH4,P_COLO2,P_CO2MULT, P_COLBRD, K_LAYTROP,K_LAYSWTCH,K_LAYLOW,PAVEL,P_TAVEL,P_SELFFAC,P_SELFFRAC,K_INDSELF, K_INDMINOR,P_SCALEMINOR,P_SCALEMINORN2,P_MINORFRAC, PRAT_H2OCO2, PRAT_H2OCO2_1, PRAT_H2OO3, PRAT_H2OO3_1, PRAT_H2ON2O, PRAT_H2ON2O_1, PRAT_H2OCH4, PRAT_H2OCH4_1, PRAT_N2OCO2, PRAT_N2OCO2_1, PRAT_O3CO2, PRAT_O3CO2_1)
    type(longwave_reference_parameter_record), intent(in) :: owned_reference
    TYPE(TDIMV), INTENT(IN) :: YDDIMV
    INTEGER(KIND=JPIM), INTENT(IN) :: KIDIA
    INTEGER(KIND=JPIM), INTENT(IN) :: KFDIA
    INTEGER(KIND=JPIM), INTENT(IN) :: KLEV
    REAL(KIND=JPRB), INTENT(IN) :: P_COLDRY(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(IN) :: P_WBROAD(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(INOUT) :: P_COLBRD(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(IN) :: P_WKL(KIDIA:KFDIA, 35, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(INOUT) :: P_FAC00(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(INOUT) :: P_FAC01(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(INOUT) :: P_FAC10(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(INOUT) :: P_FAC11(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(INOUT) :: P_FORFAC(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(INOUT) :: P_FORFRAC(KIDIA:KFDIA, YDDIMV%NFLEVG)
    INTEGER(KIND=JPIM), INTENT(INOUT) :: K_JP(KIDIA:KFDIA, YDDIMV%NFLEVG)
    INTEGER(KIND=JPIM), INTENT(INOUT) :: K_JT(KIDIA:KFDIA, YDDIMV%NFLEVG)
    INTEGER(KIND=JPIM), INTENT(INOUT) :: K_JT1(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(INOUT) :: P_COLH2O(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(INOUT) :: P_COLCO2(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(INOUT) :: P_COLO3(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(INOUT) :: P_COLN2O(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(INOUT) :: P_COLCH4(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(INOUT) :: P_COLO2(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(INOUT) :: P_CO2MULT(KIDIA:KFDIA, YDDIMV%NFLEVG)
    INTEGER(KIND=JPIM), INTENT(INOUT) :: K_LAYTROP(KIDIA:KFDIA)
    INTEGER(KIND=JPIM), INTENT(INOUT) :: K_LAYSWTCH(KIDIA:KFDIA)
    INTEGER(KIND=JPIM), INTENT(INOUT) :: K_LAYLOW(KIDIA:KFDIA)
    REAL(KIND=JPRB), INTENT(IN) :: PAVEL(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(IN) :: P_TAVEL(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(INOUT) :: P_SELFFAC(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(INOUT) :: P_SELFFRAC(KIDIA:KFDIA, YDDIMV%NFLEVG)
    INTEGER(KIND=JPIM), INTENT(INOUT) :: K_INDSELF(KIDIA:KFDIA, YDDIMV%NFLEVG)
    INTEGER(KIND=JPIM), INTENT(INOUT) :: K_INDFOR(KIDIA:KFDIA, YDDIMV%NFLEVG)
    INTEGER(KIND=JPIM), INTENT(INOUT) :: K_INDMINOR(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(INOUT) :: P_SCALEMINOR(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(INOUT) :: P_SCALEMINORN2(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(INOUT) :: P_MINORFRAC(KIDIA:KFDIA, YDDIMV%NFLEVG)
  REAL(KIND=JPRB)   ,INTENT(INOUT)   :: PRAT_H2OCO2(KIDIA:KFDIA,YDDIMV%NFLEVG),PRAT_H2OCO2_1(KIDIA:KFDIA,YDDIMV%NFLEVG), PRAT_H2OO3(KIDIA:KFDIA,YDDIMV%NFLEVG) ,PRAT_H2OO3_1(KIDIA:KFDIA,YDDIMV%NFLEVG), PRAT_H2ON2O(KIDIA:KFDIA,YDDIMV%NFLEVG),PRAT_H2ON2O_1(KIDIA:KFDIA,YDDIMV%NFLEVG), PRAT_H2OCH4(KIDIA:KFDIA,YDDIMV%NFLEVG),PRAT_H2OCH4_1(KIDIA:KFDIA,YDDIMV%NFLEVG), PRAT_N2OCO2(KIDIA:KFDIA,YDDIMV%NFLEVG),PRAT_N2OCO2_1(KIDIA:KFDIA,YDDIMV%NFLEVG), PRAT_O3CO2(KIDIA:KFDIA,YDDIMV%NFLEVG) ,PRAT_O3CO2_1(KIDIA:KFDIA,YDDIMV%NFLEVG)
    INTEGER(KIND=JPIM) :: JP1, JLAY
    INTEGER(KIND=JPIM) :: JLON
    REAL(KIND=JPRB) :: Z_CO2REG, Z_COMPFP, Z_FACTOR, Z_FP, Z_FT, Z_FT1, Z_PLOG, Z_SCALEFAC, Z_STPFAC, Z_WATER
    ASSOCIATE (NFLEVG => YDDIMV%NFLEVG)
    DO JLON = KIDIA, KFDIA
      Z_STPFAC = 296._JPRB/1013._JPRB
      K_LAYTROP(JLON) = 0
      K_LAYSWTCH(JLON) = 0
      K_LAYLOW(JLON) = 0
      DO JLAY = 1, KLEV
        Z_PLOG = LOG(PAVEL(JLON, JLAY))
        K_JP(JLON, JLAY) = INT(36._JPRB - 5*(Z_PLOG + 0.04_JPRB))
        IF (K_JP(JLON, JLAY) < 1) THEN
          K_JP(JLON, JLAY) = 1
        ELSEIF (K_JP(JLON, JLAY) > 58) THEN
          K_JP(JLON, JLAY) = 58
        END IF
        JP1 = K_JP(JLON, JLAY) + 1
        Z_FP = 5._JPRB*(owned_reference%preflog(K_JP(JLON, JLAY)) - Z_PLOG)
        Z_FP = MAX(-1._JPRB, MIN(1._JPRB, Z_FP))
        K_JT(JLON, JLAY) = INT(3._JPRB + (P_TAVEL(JLON, JLAY) - owned_reference%tref(K_JP(JLON, JLAY)))/15._JPRB)
        IF (K_JT(JLON, JLAY) < 1) THEN
          K_JT(JLON, JLAY) = 1
        ELSEIF (K_JT(JLON, JLAY) > 4) THEN
          K_JT(JLON, JLAY) = 4
        END IF
        Z_FT = ((P_TAVEL(JLON, JLAY) - owned_reference%tref(K_JP(JLON, JLAY)))/15._JPRB) - REAL(K_JT(JLON, JLAY) - 3)
        K_JT1(JLON, JLAY) = INT(3._JPRB + (P_TAVEL(JLON, JLAY) - owned_reference%tref(JP1))/15._JPRB)
        IF (K_JT1(JLON, JLAY) < 1) THEN
          K_JT1(JLON, JLAY) = 1
        ELSEIF (K_JT1(JLON, JLAY) > 4) THEN
          K_JT1(JLON, JLAY) = 4
        END IF
        Z_FT1 = ((P_TAVEL(JLON, JLAY) - owned_reference%tref(JP1))/15._JPRB) - REAL(K_JT1(JLON, JLAY) - 3)
        Z_WATER = P_WKL(JLON, 1, JLAY)/P_COLDRY(JLON, JLAY)
        Z_SCALEFAC = PAVEL(JLON, JLAY)*Z_STPFAC/P_TAVEL(JLON, JLAY)
        IF (Z_PLOG > 4.56_JPRB) THEN
          K_LAYTROP(JLON) = K_LAYTROP(JLON) + 1
          P_FORFAC(JLON, JLAY) = Z_SCALEFAC/(1.0_JPRB + Z_WATER)
          Z_FACTOR = (332.0_JPRB - P_TAVEL(JLON, JLAY))/36.0_JPRB
          K_INDFOR(JLON, JLAY) = MIN(2, MAX(1, INT(Z_FACTOR)))
          P_FORFRAC(JLON, JLAY) = Z_FACTOR - REAL(K_INDFOR(JLON, JLAY))
          P_SELFFAC(JLON, JLAY) = Z_WATER*P_FORFAC(JLON, JLAY)
          Z_FACTOR = (P_TAVEL(JLON, JLAY) - 188.0_JPRB)/7.2_JPRB
          K_INDSELF(JLON, JLAY) = MIN(9, MAX(1, INT(Z_FACTOR) - 7))
          P_SELFFRAC(JLON, JLAY) = Z_FACTOR - REAL(K_INDSELF(JLON, JLAY) + 7)
          P_SCALEMINOR(JLON, JLAY) = PAVEL(JLON, JLAY)/P_TAVEL(JLON, JLAY)
   P_SCALEMINORN2(JLON,JLAY) = (PAVEL(JLON,JLAY)/P_TAVEL(JLON,JLAY)) *(P_WBROAD(JLON,JLAY)/(P_COLDRY(JLON,JLAY)+P_WKL(JLON,1,JLAY)))
          Z_FACTOR = (P_TAVEL(JLON, JLAY) - 180.8_JPRB)/7.2_JPRB
          K_INDMINOR(JLON, JLAY) = MIN(18, MAX(1, INT(Z_FACTOR)))
          P_MINORFRAC(JLON, JLAY) = Z_FACTOR - REAL(K_INDMINOR(JLON, JLAY))
          PRAT_H2OCO2(JLON, JLAY) = owned_reference%chi_mls(1, K_JP(JLON, JLAY))/owned_reference%chi_mls(2, K_JP(JLON, JLAY))
       PRAT_H2OCO2_1(JLON, JLAY) = owned_reference%chi_mls(1, K_JP(JLON, JLAY) + 1)/owned_reference%chi_mls(2, K_JP(JLON, JLAY) + 1)
          PRAT_H2OO3(JLON, JLAY) = owned_reference%chi_mls(1, K_JP(JLON, JLAY))/owned_reference%chi_mls(3, K_JP(JLON, JLAY))
        PRAT_H2OO3_1(JLON, JLAY) = owned_reference%chi_mls(1, K_JP(JLON, JLAY) + 1)/owned_reference%chi_mls(3, K_JP(JLON, JLAY) + 1)
          PRAT_H2ON2O(JLON, JLAY) = owned_reference%chi_mls(1, K_JP(JLON, JLAY))/owned_reference%chi_mls(4, K_JP(JLON, JLAY))
       PRAT_H2ON2O_1(JLON, JLAY) = owned_reference%chi_mls(1, K_JP(JLON, JLAY) + 1)/owned_reference%chi_mls(4, K_JP(JLON, JLAY) + 1)
          PRAT_H2OCH4(JLON, JLAY) = owned_reference%chi_mls(1, K_JP(JLON, JLAY))/owned_reference%chi_mls(6, K_JP(JLON, JLAY))
       PRAT_H2OCH4_1(JLON, JLAY) = owned_reference%chi_mls(1, K_JP(JLON, JLAY) + 1)/owned_reference%chi_mls(6, K_JP(JLON, JLAY) + 1)
          PRAT_N2OCO2(JLON, JLAY) = owned_reference%chi_mls(4, K_JP(JLON, JLAY))/owned_reference%chi_mls(2, K_JP(JLON, JLAY))
       PRAT_N2OCO2_1(JLON, JLAY) = owned_reference%chi_mls(4, K_JP(JLON, JLAY) + 1)/owned_reference%chi_mls(2, K_JP(JLON, JLAY) + 1)
          P_COLH2O(JLON, JLAY) = 1.E-20_JPRB*P_WKL(JLON, 1, JLAY)
          P_COLCO2(JLON, JLAY) = 1.E-20_JPRB*P_WKL(JLON, 2, JLAY)
          P_COLO3(JLON, JLAY) = 1.E-20_JPRB*P_WKL(JLON, 3, JLAY)
          P_COLN2O(JLON, JLAY) = 1.E-20_JPRB*P_WKL(JLON, 4, JLAY)
          P_COLCH4(JLON, JLAY) = 1.E-20_JPRB*P_WKL(JLON, 6, JLAY)
          P_COLO2(JLON, JLAY) = 1.E-20_JPRB*P_WKL(JLON, 7, JLAY)
          P_COLBRD(JLON, JLAY) = 1.E-20_JPRB*P_WBROAD(JLON, JLAY)
          IF (P_COLCO2(JLON, JLAY) == 0.0_JPRB) P_COLCO2(JLON, JLAY) = 1.E-32_JPRB*P_COLDRY(JLON, JLAY)
          IF (P_COLN2O(JLON, JLAY) == 0.0_JPRB) P_COLN2O(JLON, JLAY) = 1.E-32_JPRB*P_COLDRY(JLON, JLAY)
          IF (P_COLCH4(JLON, JLAY) == 0.0_JPRB) P_COLCH4(JLON, JLAY) = 1.E-32_JPRB*P_COLDRY(JLON, JLAY)
          Z_CO2REG = 3.55E-24_JPRB*P_COLDRY(JLON, JLAY)
  P_CO2MULT(JLON,JLAY)= (P_COLCO2(JLON,JLAY) - Z_CO2REG) * 272.63_JPRB*EXP(-1919.4_JPRB/P_TAVEL(JLON,JLAY))/(8.7604E-4_JPRB*P_TAVEL(JLON,JLAY))
        ELSE
          P_FORFAC(JLON, JLAY) = Z_SCALEFAC/(1.0_JPRB + Z_WATER)
          Z_FACTOR = (P_TAVEL(JLON, JLAY) - 188.0_JPRB)/36.0_JPRB
          K_INDFOR(JLON, JLAY) = 3
          P_FORFRAC(JLON, JLAY) = Z_FACTOR - 1.0_JPRB
          P_SELFFAC(JLON, JLAY) = Z_WATER*P_FORFAC(JLON, JLAY)
          P_SCALEMINOR(JLON, JLAY) = PAVEL(JLON, JLAY)/P_TAVEL(JLON, JLAY)
  P_SCALEMINORN2(JLON,JLAY) = (PAVEL(JLON,JLAY)/P_TAVEL(JLON,JLAY)) * (P_WBROAD(JLON,JLAY)/(P_COLDRY(JLON,JLAY)+P_WKL(JLON,1,JLAY)))
          Z_FACTOR = (P_TAVEL(JLON, JLAY) - 180.8_JPRB)/7.2_JPRB
          K_INDMINOR(JLON, JLAY) = MIN(18, MAX(1, INT(Z_FACTOR)))
          P_MINORFRAC(JLON, JLAY) = Z_FACTOR - REAL(K_INDMINOR(JLON, JLAY))
          PRAT_H2OCO2(JLON, JLAY) = owned_reference%chi_mls(1, K_JP(JLON, JLAY))/owned_reference%chi_mls(2, K_JP(JLON, JLAY))
       PRAT_H2OCO2_1(JLON, JLAY) = owned_reference%chi_mls(1, K_JP(JLON, JLAY) + 1)/owned_reference%chi_mls(2, K_JP(JLON, JLAY) + 1)
          PRAT_O3CO2(JLON, JLAY) = owned_reference%chi_mls(3, K_JP(JLON, JLAY))/owned_reference%chi_mls(2, K_JP(JLON, JLAY))
        PRAT_O3CO2_1(JLON, JLAY) = owned_reference%chi_mls(3, K_JP(JLON, JLAY) + 1)/owned_reference%chi_mls(2, K_JP(JLON, JLAY) + 1)
          P_COLH2O(JLON, JLAY) = 1.E-20_JPRB*P_WKL(JLON, 1, JLAY)
          P_COLCO2(JLON, JLAY) = 1.E-20_JPRB*P_WKL(JLON, 2, JLAY)
          P_COLO3(JLON, JLAY) = 1.E-20_JPRB*P_WKL(JLON, 3, JLAY)
          P_COLN2O(JLON, JLAY) = 1.E-20_JPRB*P_WKL(JLON, 4, JLAY)
          P_COLCH4(JLON, JLAY) = 1.E-20_JPRB*P_WKL(JLON, 6, JLAY)
          P_COLO2(JLON, JLAY) = 1.E-20_JPRB*P_WKL(JLON, 7, JLAY)
          P_COLBRD(JLON, JLAY) = 1.E-20_JPRB*P_WBROAD(JLON, JLAY)
          IF (P_COLCO2(JLON, JLAY) == 0.0_JPRB) P_COLCO2(JLON, JLAY) = 1.E-32_JPRB*P_COLDRY(JLON, JLAY)
          IF (P_COLN2O(JLON, JLAY) == 0.0_JPRB) P_COLN2O(JLON, JLAY) = 1.E-32_JPRB*P_COLDRY(JLON, JLAY)
          IF (P_COLCH4(JLON, JLAY) == 0.0_JPRB) P_COLCH4(JLON, JLAY) = 1.E-32_JPRB*P_COLDRY(JLON, JLAY)
          Z_CO2REG = 3.55E-24_JPRB*P_COLDRY(JLON, JLAY)
  P_CO2MULT(JLON,JLAY)= (P_COLCO2(JLON,JLAY) - Z_CO2REG) * 272.63_JPRB*EXP(-1919.4_JPRB/P_TAVEL(JLON,JLAY))/(8.7604E-4_JPRB*P_TAVEL(JLON,JLAY))
        END IF
        Z_COMPFP = 1.0_JPRB - Z_FP
        P_FAC10(JLON, JLAY) = Z_COMPFP*Z_FT
        P_FAC00(JLON, JLAY) = Z_COMPFP*(1.0_JPRB - Z_FT)
        P_FAC11(JLON, JLAY) = Z_FP*Z_FT1
        P_FAC01(JLON, JLAY) = Z_FP*(1.0_JPRB - Z_FT1)
        P_SELFFAC(JLON, JLAY) = P_COLH2O(JLON, JLAY)*P_SELFFAC(JLON, JLAY)
        P_FORFAC(JLON, JLAY) = P_COLH2O(JLON, JLAY)*P_FORFAC(JLON, JLAY)
      END DO
      IF (K_LAYLOW(JLON) == 0) K_LAYLOW(JLON) = 1
    END DO
    END ASSOCIATE
  end subroutine rrtm_setcoef_140gp
end module
