!> Complete sixteen-band longwave call order and lossless output transfer.
!! Canonical TDIMV supplies the level capacity; selected columns may have shifted labels.
!! POD stores spectral point, level and column; PFRAC stores column, point and level.
!! Both dimensionless FP64 owners retain inactive level tails. Inputs are disjoint.
!! Coefficient records are readonly; this routine owns and releases one native workspace.
!! Scientific source attribution: R. J. Hogan, ECMWF and AER RRTM.
module native_longwave_gas_optical_depth
  use iso_fortran_env, only: JPIM => int32, JPRB => real64, int64
  use iso_c_binding, only: c_int
  use yomdimv, only: TDIMV
  use native_absorption_records, only: longwave_absorption_reduced_record
  use longwave_reference_parameter_fields_mod, only: longwave_reference_parameter_record
  use native_rrtm_taumol1, only: rrtm_taumol1
  use native_rrtm_taumol2, only: rrtm_taumol2
  use native_rrtm_taumol3, only: rrtm_taumol3
  use native_rrtm_taumol4, only: rrtm_taumol4
  use native_rrtm_taumol5, only: rrtm_taumol5
  use native_rrtm_taumol6, only: rrtm_taumol6
  use native_rrtm_taumol7, only: rrtm_taumol7
  use native_rrtm_taumol8, only: rrtm_taumol8
  use native_rrtm_taumol9, only: rrtm_taumol9
  use native_rrtm_taumol10, only: rrtm_taumol10
  use native_rrtm_taumol11, only: rrtm_taumol11
  use native_rrtm_taumol12, only: rrtm_taumol12
  use native_rrtm_taumol13, only: rrtm_taumol13
  use native_rrtm_taumol14, only: rrtm_taumol14
  use native_rrtm_taumol15, only: rrtm_taumol15
  use native_rrtm_taumol16, only: rrtm_taumol16
  implicit none
  private
  public :: rrtm_gas_optical_depth
  integer, parameter :: JPGPT = 140, JPBAND = 16, JPXSEC = 4
  interface
    subroutine public_abort() bind(C, name="abort")
    end subroutine
  end interface
contains
!> Join complete bands in increasing order, including empty work.
!! Caller admits 0:4096 columns, 0:512 active and supplied levels,
!! supplied levels at least active levels, and nearest-even gradual FP64.
!! The workspace has exactly 140*n*supplied_levels real64 cells;
!! a zero extent remains a valid native allocation and all child calls remain.
SUBROUTINE RRTM_GAS_OPTICAL_DEPTH(owned_reference,owned_coefficients,YDDIMV,KIDIA,KFDIA,KLEV,POD,PAVEL, PCOLDRY,PCOLBRD,PWX, PTAUAERL,PFAC00,PFAC01,PFAC10,PFAC11,PFORFAC,PFORFRAC,KINDFOR,KJP,KJT,KJT1,PONEMINUS, PCOLH2O,PCOLCO2,PCOLO3,PCOLN2O,PCOLCH4,PCOLO2,P_CO2MULT, KLAYTROP,KLAYSWTCH,KLAYLOW,PSELFFAC,PSELFFRAC,KINDSELF,PFRAC, KINDMINOR,PSCALEMINOR,PSCALEMINORN2,PMINORFRAC, PRAT_H2OCO2, PRAT_H2OCO2_1, PRAT_H2OO3, PRAT_H2OO3_1, PRAT_H2ON2O, PRAT_H2ON2O_1, PRAT_H2OCH4, PRAT_H2OCH4_1, PRAT_N2OCO2, PRAT_N2OCO2_1, PRAT_O3CO2, PRAT_O3CO2_1)
    type(longwave_reference_parameter_record), intent(in) :: owned_reference
    type(longwave_absorption_reduced_record), target, intent(in) :: owned_coefficients
    TYPE(TDIMV), INTENT(IN) :: YDDIMV
    INTEGER(KIND=JPIM), INTENT(IN) :: KIDIA
    INTEGER(KIND=JPIM), INTENT(IN) :: KFDIA
    INTEGER(KIND=JPIM), INTENT(IN) :: KLEV
    REAL(KIND=JPRB), INTENT(INOUT) :: POD(JPGPT, YDDIMV%NFLEVG, KIDIA:KFDIA)
    REAL(KIND=JPRB), INTENT(IN) :: PAVEL(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(IN) :: PCOLDRY(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(IN) :: PWX(KIDIA:KFDIA, JPXSEC, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(IN) :: PTAUAERL(KIDIA:KFDIA, YDDIMV%NFLEVG, JPBAND)
    REAL(KIND=JPRB), INTENT(IN) :: PFAC00(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(IN) :: PFAC01(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(IN) :: PFAC10(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(IN) :: PFAC11(KIDIA:KFDIA, YDDIMV%NFLEVG)
    INTEGER(KIND=JPIM), INTENT(IN) :: KJP(KIDIA:KFDIA, YDDIMV%NFLEVG)
    INTEGER(KIND=JPIM), INTENT(IN) :: KJT(KIDIA:KFDIA, YDDIMV%NFLEVG)
    INTEGER(KIND=JPIM), INTENT(IN) :: KJT1(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(IN) :: PONEMINUS
    REAL(KIND=JPRB), INTENT(IN) :: PCOLH2O(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(IN) :: PCOLCO2(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(IN) :: PCOLO3(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(IN) :: PCOLN2O(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(IN) :: PCOLCH4(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(IN) :: PCOLO2(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(IN) :: P_CO2MULT(KIDIA:KFDIA, YDDIMV%NFLEVG)
    INTEGER(KIND=JPIM), INTENT(IN) :: KLAYTROP(KIDIA:KFDIA)
    INTEGER(KIND=JPIM), INTENT(IN) :: KLAYSWTCH(KIDIA:KFDIA)
    INTEGER(KIND=JPIM), INTENT(IN) :: KLAYLOW(KIDIA:KFDIA)
    REAL(KIND=JPRB), INTENT(IN) :: PSELFFAC(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(IN) :: PSELFFRAC(KIDIA:KFDIA, YDDIMV%NFLEVG)
    INTEGER(KIND=JPIM), INTENT(IN) :: KINDSELF(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(INOUT) :: PFRAC(KIDIA:KFDIA, JPGPT, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(IN) :: PFORFAC(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(IN) :: PFORFRAC(KIDIA:KFDIA, YDDIMV%NFLEVG)
    INTEGER(KIND=JPIM), INTENT(IN) :: KINDFOR(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(IN) :: PMINORFRAC(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(IN) :: PSCALEMINOR(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(IN) :: PSCALEMINORN2(KIDIA:KFDIA, YDDIMV%NFLEVG)
    INTEGER(KIND=JPIM), INTENT(IN) :: KINDMINOR(KIDIA:KFDIA, YDDIMV%NFLEVG)
    REAL(KIND=JPRB), INTENT(IN) :: PCOLBRD(KIDIA:KFDIA, YDDIMV%NFLEVG)
REAL(KIND=JPRB)  , INTENT(IN) :: PRAT_H2OCO2(KIDIA:KFDIA,YDDIMV%NFLEVG),PRAT_H2OCO2_1(KIDIA:KFDIA,YDDIMV%NFLEVG), PRAT_H2OO3(KIDIA:KFDIA,YDDIMV%NFLEVG),PRAT_H2OO3_1(KIDIA:KFDIA,YDDIMV%NFLEVG), PRAT_H2ON2O(KIDIA:KFDIA,YDDIMV%NFLEVG),PRAT_H2ON2O_1(KIDIA:KFDIA,YDDIMV%NFLEVG), PRAT_H2OCH4(KIDIA:KFDIA,YDDIMV%NFLEVG),PRAT_H2OCH4_1(KIDIA:KFDIA,YDDIMV%NFLEVG), PRAT_N2OCO2(KIDIA:KFDIA,YDDIMV%NFLEVG),PRAT_N2OCO2_1(KIDIA:KFDIA,YDDIMV%NFLEVG), PRAT_O3CO2(KIDIA:KFDIA,YDDIMV%NFLEVG),PRAT_O3CO2_1(KIDIA:KFDIA,YDDIMV%NFLEVG)
    INTEGER(KIND=JPIM) :: JI, JLEV
    INTEGER(KIND=JPIM) :: JLON
    real(JPRB), allocatable, target :: workspace(:)
    real(JPRB), pointer, contiguous :: ztau(:, :, :)
    integer(int64) :: workspace_words
    integer :: allocation_status
    workspace_words = int(max(0, KFDIA - KIDIA + 1), int64)*140_int64*int(YDDIMV%NFLEVG, int64)
    allocate (workspace(workspace_words), stat=allocation_status)
    if (allocation_status /= 0) call public_abort()
    ztau(KIDIA:KFDIA, 1:140, 1:YDDIMV%NFLEVG) => workspace
    ASSOCIATE (NFLEVG => YDDIMV%NFLEVG)
CALL RRTM_TAUMOL1(owned_reference,owned_coefficients,YDDIMV,KIDIA,KFDIA,KLEV,ZTAU,PAVEL, PTAUAERL,PFAC00,PFAC01,PFAC10,PFAC11,PFORFAC,PFORFRAC,KINDFOR,KJP,KJT,KJT1, PCOLH2O,KLAYTROP,PSELFFAC,PSELFFRAC,KINDSELF,PFRAC, PMINORFRAC, KINDMINOR,PSCALEMINORN2,PCOLBRD)
CALL RRTM_TAUMOL2(owned_reference,owned_coefficients,YDDIMV,KIDIA,KFDIA,KLEV,ZTAU,PAVEL,PCOLDRY, PTAUAERL,PFAC00,PFAC01,PFAC10,PFAC11,PFORFAC,PFORFRAC,KINDFOR,KJP,KJT,KJT1, PCOLH2O,KLAYTROP,PSELFFAC,PSELFFRAC,KINDSELF,PFRAC)
CALL RRTM_TAUMOL3(owned_reference,owned_coefficients,YDDIMV,KIDIA,KFDIA,KLEV,ZTAU, PTAUAERL,PFAC00,PFAC01,PFAC10,PFAC11,PFORFAC,PFORFRAC,KINDFOR,KJP,KJT,KJT1,PONEMINUS, PCOLH2O,PCOLCO2,PCOLN2O,PCOLDRY,KLAYTROP,PSELFFAC,PSELFFRAC,KINDSELF,PFRAC, PRAT_H2OCO2, PRAT_H2OCO2_1,PMINORFRAC,KINDMINOR)
CALL RRTM_TAUMOL4(owned_reference,owned_coefficients,YDDIMV,KIDIA,KFDIA,KLEV,ZTAU, PTAUAERL,PFAC00,PFAC01,PFAC10,PFAC11,PFORFAC,PFORFRAC,KINDFOR,KJP,KJT,KJT1,PONEMINUS, PCOLH2O,PCOLCO2,PCOLO3,KLAYTROP,PSELFFAC,PSELFFRAC,KINDSELF,PFRAC, PRAT_H2OCO2, PRAT_H2OCO2_1, PRAT_O3CO2, PRAT_O3CO2_1)
CALL RRTM_TAUMOL5(owned_reference,owned_coefficients,YDDIMV,KIDIA,KFDIA,KLEV,ZTAU,PWX, PTAUAERL,PFAC00,PFAC01,PFAC10,PFAC11,PFORFAC,PFORFRAC,KINDFOR,KJP,KJT,KJT1,PONEMINUS, PCOLH2O,PCOLCO2,PCOLO3,KLAYTROP,PSELFFAC,PSELFFRAC,KINDSELF,PFRAC, PRAT_H2OCO2, PRAT_H2OCO2_1, PRAT_O3CO2, PRAT_O3CO2_1,PMINORFRAC,KINDMINOR)
CALL RRTM_TAUMOL6(owned_reference,owned_coefficients,YDDIMV,KIDIA,KFDIA,KLEV,ZTAU,PWX, PTAUAERL,PFAC00,PFAC01,PFAC10,PFAC11,PFORFAC,PFORFRAC,KINDFOR,KJP,KJT,KJT1, PCOLH2O,PCOLCO2,PCOLDRY,KLAYTROP,PSELFFAC,PSELFFRAC,KINDSELF,PFRAC,PMINORFRAC,KINDMINOR)
CALL RRTM_TAUMOL7(owned_reference,owned_coefficients,YDDIMV,KIDIA,KFDIA,KLEV,ZTAU, PTAUAERL,PFAC00,PFAC01,PFAC10,PFAC11,PFORFAC,PFORFRAC,KINDFOR,KJP,KJT,KJT1,PONEMINUS, PCOLH2O,PCOLO3,PCOLCO2,PCOLDRY,KLAYTROP,PSELFFAC,PSELFFRAC,KINDSELF,PFRAC, PRAT_H2OO3, PRAT_H2OO3_1,PMINORFRAC,KINDMINOR)
CALL RRTM_TAUMOL8(owned_reference,owned_coefficients,YDDIMV,KIDIA,KFDIA,KLEV,ZTAU,PWX, PTAUAERL,PFAC00,PFAC01,PFAC10,PFAC11,PFORFAC,PFORFRAC,KINDFOR,KJP,KJT,KJT1, PCOLH2O,PCOLO3,PCOLN2O,PCOLCO2,PCOLDRY,KLAYTROP,PSELFFAC,PSELFFRAC,KINDSELF,PFRAC, PMINORFRAC,KINDMINOR)
CALL RRTM_TAUMOL9(owned_reference,owned_coefficients,YDDIMV,KIDIA,KFDIA,KLEV,ZTAU, PTAUAERL,PFAC00,PFAC01,PFAC10,PFAC11,PFORFAC,PFORFRAC,KINDFOR,KJP,KJT,KJT1,PONEMINUS, PCOLH2O,PCOLN2O,PCOLCH4,PCOLDRY,KLAYTROP,KLAYSWTCH,KLAYLOW,PSELFFAC,PSELFFRAC,KINDSELF,PFRAC, PRAT_H2OCH4,PRAT_H2OCH4_1,PMINORFRAC,KINDMINOR)
CALL RRTM_TAUMOL10(owned_reference,owned_coefficients,YDDIMV,KIDIA,KFDIA,KLEV,ZTAU, PTAUAERL,PFAC00,PFAC01,PFAC10,PFAC11,PFORFAC,PFORFRAC,KINDFOR,KJP,KJT,KJT1, PCOLH2O,KLAYTROP,PSELFFAC,PSELFFRAC,KINDSELF,PFRAC)
CALL RRTM_TAUMOL11(owned_reference,owned_coefficients,YDDIMV,KIDIA,KFDIA,KLEV,ZTAU, PTAUAERL,PFAC00,PFAC01,PFAC10,PFAC11,PFORFAC,PFORFRAC,KINDFOR,KJP,KJT,KJT1, PCOLH2O,PCOLO2,KLAYTROP,PSELFFAC,PSELFFRAC,KINDSELF,PFRAC,PMINORFRAC,KINDMINOR,PSCALEMINOR)
CALL RRTM_TAUMOL12(owned_reference,owned_coefficients,YDDIMV,KIDIA,KFDIA,KLEV,ZTAU, PTAUAERL,PFAC00,PFAC01,PFAC10,PFAC11,PFORFAC,PFORFRAC,KINDFOR,KJP,KJT,KJT1,PONEMINUS, PCOLH2O,PCOLCO2,KLAYTROP,PSELFFAC,PSELFFRAC,KINDSELF,PFRAC, PRAT_H2OCO2, PRAT_H2OCO2_1)
CALL RRTM_TAUMOL13(owned_reference,owned_coefficients,YDDIMV,KIDIA,KFDIA,KLEV,ZTAU, PTAUAERL,PFAC00,PFAC01,PFAC10,PFAC11,PFORFAC,PFORFRAC,KINDFOR,KJP,KJT,KJT1,PONEMINUS, PCOLH2O,PCOLN2O,PCOLCO2,PCOLO3,PCOLDRY,KLAYTROP,PSELFFAC,PSELFFRAC,KINDSELF,PFRAC, PRAT_H2ON2O, PRAT_H2ON2O_1,PMINORFRAC,KINDMINOR)
CALL RRTM_TAUMOL14(owned_reference,owned_coefficients,YDDIMV,KIDIA,KFDIA,KLEV,ZTAU, PTAUAERL,PFAC00,PFAC01,PFAC10,PFAC11,PFORFAC,PFORFRAC,KINDFOR,KJP,KJT,KJT1, PCOLCO2,KLAYTROP,PSELFFAC,PSELFFRAC,KINDSELF,PFRAC)
CALL RRTM_TAUMOL15(owned_reference,owned_coefficients,YDDIMV,KIDIA,KFDIA,KLEV,ZTAU, PTAUAERL,PFAC00,PFAC01,PFAC10,PFAC11,PFORFAC,PFORFRAC,KINDFOR,KJP,KJT,KJT1,PONEMINUS, PCOLH2O,PCOLCO2,PCOLN2O,KLAYTROP,PSELFFAC,PSELFFRAC,KINDSELF,PFRAC, PRAT_N2OCO2, PRAT_N2OCO2_1,PMINORFRAC,KINDMINOR,PSCALEMINOR,PCOLBRD)
CALL RRTM_TAUMOL16(owned_reference,owned_coefficients,YDDIMV,KIDIA,KFDIA,KLEV,ZTAU, PTAUAERL,PFAC00,PFAC01,PFAC10,PFAC11,PFORFAC,PFORFRAC,KINDFOR,KJP,KJT,KJT1,PONEMINUS, PCOLH2O,PCOLCH4,KLAYTROP,PSELFFAC,PSELFFRAC,KINDSELF,PFRAC, PRAT_H2OCH4,PRAT_H2OCH4_1)
      DO JLEV = 1, KLEV
      DO JI = 1, JPGPT
      DO JLON = KIDIA, KFDIA
        POD(JI, JLEV, JLON) = ZTAU(JLON, JI, JLEV)
      END DO
      END DO
      END DO
    END ASSOCIATE
    nullify (ztau)
    deallocate (workspace)
  END SUBROUTINE RRTM_GAS_OPTICAL_DEPTH
end module
