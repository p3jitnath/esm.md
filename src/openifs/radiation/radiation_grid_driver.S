/* Load a large fixed integer without changing any numerical value. */
.macro grid_integer reg, value
 movz \reg, #(\value & 65535)
 movk \reg, #((\value >> 16) & 65535), lsl #16
.endm
/* A source-model word is loaded through the private complete model owner. */
.macro grid_model address, offset
 grid_integer \address, \offset
 add \address, x19, \address
.endm
/* Each external call keeps the platform register unchanged. */
.macro grid_call symbol
 str x18,[x29,#2800]
 bl \symbol
 ldr x18,[x29,#2800]
.endm
/* x0 is the private vector, x1 the solar output, x2 the original model.
 * The coefficient remains a captured FP64 value, with no contraction.
