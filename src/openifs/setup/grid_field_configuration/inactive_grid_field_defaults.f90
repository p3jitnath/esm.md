  integer(int32) function initialize_selected_inactive_grid_defaults(state, controls, settings, profiles) result(status)
    type(grid_field_registration_state), intent(in) :: state
    type(grid_field_alias_controls), intent(inout) :: controls
    type(grid_field_settings), intent(inout) :: settings
    type(inactive_grid_field_profiles), intent(inout) :: profiles
    status = 2_int32
    if (.not. grid_field_mode_supported()) return
    if (state%numflds /= 8) return
    if (controls%nnogw /= 2 .or. settings%nfldsfix /= 5) return
    if (.not. inactive_grid_profiles_are_fresh(profiles)) return
    call apply_inactive_defaults(controls, settings, profiles)
    status = 0_int32
  end function
  integer(int32) function initialize_operational_inactive_grid_defaults(state, controls, settings, profiles) result(status)
    type(grid_field_registration_state), intent(in) :: state
    type(grid_field_alias_controls), intent(inout) :: controls
    type(grid_field_settings), intent(inout) :: settings
    type(inactive_grid_field_profiles), intent(inout) :: profiles
    status = 2_int32
    if (.not. grid_field_mode_supported()) return
    if (state%numflds /= 9) return
    if (controls%nnogw /= 2 .or. settings%nfldsfix /= 5) return
