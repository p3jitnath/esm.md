  integer(int32) function check_selected_fullpos_field_descriptors(afn, nprintlev, larpegef) result(status)
    type(tafn), intent(in) :: afn
    integer(int32), intent(in) :: nprintlev
    logical, intent(in) :: larpegef
    integer :: i, j
    status = 2
    if (nprintlev /= 0 .or. larpegef .or. afn%nsfxpre_cnt /= 0) return
    status = 3
    do i = 1, size(afn%tfp_dynds) - 1
      if (afn%tfp_dynds(i)%igrib <= 0) cycle
      do j = i + 1, size(afn%tfp_dynds)
        if (afn%tfp_dynds(i)%igrib == afn%tfp_dynds(j)%igrib .and. (afn%tfp_dynds(i)%llsrf .eqv. afn%tfp_dynds(j)%llsrf)) return
      end do
    end do
    do i = 1, size(afn%gfp_phyds) - 1
      if (afn%gfp_phyds(i)%igrib <= 0) cycle
      do j = i + 1, size(afn%gfp_phyds)
        if (afn%gfp_phyds(i)%igrib == afn%gfp_phyds(j)%igrib .and. (afn%gfp_phyds(i)%llsrf .eqv. afn%gfp_phyds(j)%llsrf)) return
      end do
    end do
    status = 0
  end function
