!> Native calls to the public ECTRANS service with compiler-owned interfaces.
module md2asm_external_transform_services
  use iso_fortran_env, only: int32, int64, real64
  use md2asm_transform_types, only: transform_environment_ready
  implicit none
  private
  public :: inverse_transform_service, direct_transform_service, transform_service_calls
  integer(int64), save :: completed(2) = 0_int64
  integer, parameter :: jpim = int32, jprb = real64

  INTERFACE
    SUBROUTINE INV_TRANS(PSPVOR, PSPDIV, PSPSCALAR, PSPSC3A, PSPSC3B, PSPSC2,&
     & FSPGL_PROC,&
     & LDSCDERS, LDVORGP, LDDIVGP, LDUVDER, LDLATLON, KPROMA, KVSETUV, KVSETSC, KRESOL,&
     & KVSETSC3A, KVSETSC3B, KVSETSC2,&
     & PGP, PGPUV, PGP3A, PGP3B, PGP2)

      USE ISO_FORTRAN_ENV, ONLY: JPIM => INT32, JPRB => REAL64

      IMPLICIT NONE

      REAL(KIND=JPRB), OPTIONAL, INTENT(IN) :: PSPVOR(:, :)
      REAL(KIND=JPRB), OPTIONAL, INTENT(IN) :: PSPDIV(:, :)
      REAL(KIND=JPRB), OPTIONAL, INTENT(IN) :: PSPSCALAR(:, :)
      REAL(KIND=JPRB), OPTIONAL, INTENT(IN) :: PSPSC3A(:, :, :)
      REAL(KIND=JPRB), OPTIONAL, INTENT(IN) :: PSPSC3B(:, :, :)
      REAL(KIND=JPRB), OPTIONAL, INTENT(IN) :: PSPSC2(:, :)
      LOGICAL, OPTIONAL, INTENT(IN) :: LDSCDERS
      LOGICAL, OPTIONAL, INTENT(IN) :: LDVORGP
      LOGICAL, OPTIONAL, INTENT(IN) :: LDDIVGP
      LOGICAL, OPTIONAL, INTENT(IN) :: LDUVDER
      LOGICAL, OPTIONAL, INTENT(IN) :: LDLATLON
      INTEGER(KIND=JPIM), OPTIONAL, INTENT(IN) :: KPROMA
      INTEGER(KIND=JPIM), OPTIONAL, INTENT(IN) :: KVSETUV(:)
      INTEGER(KIND=JPIM), OPTIONAL, INTENT(IN) :: KVSETSC(:)
      INTEGER(KIND=JPIM), OPTIONAL, INTENT(IN) :: KVSETSC3A(:)
      INTEGER(KIND=JPIM), OPTIONAL, INTENT(IN) :: KVSETSC3B(:)
      INTEGER(KIND=JPIM), OPTIONAL, INTENT(IN) :: KVSETSC2(:)
      INTEGER(KIND=JPIM), OPTIONAL, INTENT(IN) :: KRESOL
      EXTERNAL FSPGL_PROC
      OPTIONAL FSPGL_PROC
      REAL(KIND=JPRB), OPTIONAL, INTENT(OUT) :: PGP(:, :, :)
      REAL(KIND=JPRB), OPTIONAL, INTENT(OUT) :: PGPUV(:, :, :, :)
      REAL(KIND=JPRB), OPTIONAL, INTENT(OUT) :: PGP3A(:, :, :, :)
      REAL(KIND=JPRB), OPTIONAL, INTENT(OUT) :: PGP3B(:, :, :, :)
      REAL(KIND=JPRB), OPTIONAL, INTENT(OUT) :: PGP2(:, :, :)

    END SUBROUTINE INV_TRANS

  END INTERFACE

  INTERFACE
    SUBROUTINE DIR_TRANS(PSPVOR, PSPDIV, PSPSCALAR, PSPSC3A, PSPSC3B, PSPSC2,&
    & LDLATLON, KPROMA, KVSETUV, KVSETSC, KRESOL, KVSETSC3A, KVSETSC3B, KVSETSC2,&
    & PGP, PGPUV, PGP3A, PGP3B, PGP2)

      USE ISO_FORTRAN_ENV, ONLY: JPIM => INT32, JPRB => REAL64

      IMPLICIT NONE

      REAL(KIND=JPRB), OPTIONAL, INTENT(OUT) :: PSPVOR(:, :)
      REAL(KIND=JPRB), OPTIONAL, INTENT(OUT) :: PSPDIV(:, :)
      REAL(KIND=JPRB), OPTIONAL, INTENT(OUT) :: PSPSCALAR(:, :)
      REAL(KIND=JPRB), OPTIONAL, INTENT(OUT) :: PSPSC3A(:, :, :)
      REAL(KIND=JPRB), OPTIONAL, INTENT(OUT) :: PSPSC3B(:, :, :)
      REAL(KIND=JPRB), OPTIONAL, INTENT(OUT) :: PSPSC2(:, :)
      INTEGER(KIND=JPIM), OPTIONAL, INTENT(IN) :: KPROMA
      INTEGER(KIND=JPIM), OPTIONAL, INTENT(IN) :: KVSETUV(:)
      INTEGER(KIND=JPIM), OPTIONAL, INTENT(IN) :: KVSETSC(:)
      INTEGER(KIND=JPIM), OPTIONAL, INTENT(IN) :: KVSETSC3A(:)
      INTEGER(KIND=JPIM), OPTIONAL, INTENT(IN) :: KVSETSC3B(:)
      INTEGER(KIND=JPIM), OPTIONAL, INTENT(IN) :: KVSETSC2(:)
      INTEGER(KIND=JPIM), OPTIONAL, INTENT(IN) :: KRESOL
      LOGICAL, OPTIONAL, INTENT(IN) :: LDLATLON

      REAL(KIND=JPRB), OPTIONAL, INTENT(IN) :: PGP(:, :, :)
      REAL(KIND=JPRB), OPTIONAL, INTENT(IN) :: PGPUV(:, :, :, :)
      REAL(KIND=JPRB), OPTIONAL, INTENT(IN) :: PGP3A(:, :, :, :)
      REAL(KIND=JPRB), OPTIONAL, INTENT(IN) :: PGP3B(:, :, :, :)
      REAL(KIND=JPRB), OPTIONAL, INTENT(IN) :: PGP2(:, :, :)

    END SUBROUTINE DIR_TRANS

  END INTERFACE
contains
!> Forward explicitly present arrays to the public transform library.
!! Arrays retain their physical units and source field order. Status2 refuses
!! an absent resolution, invalid block length or unsupported callback before the call.
subroutine inverse_transform_service(PSPVOR,PSPDIV,PSPSCALAR,PSPSC3A,PSPSC3B,PSPSC2,FSPGL_PROC,LDSCDERS,LDVORGP,LDDIVGP,LDUVDER,LDLATLON,KPROMA,KVSETUV,KVSETSC,KRESOL,KVSETSC3A,KVSETSC3B,KVSETSC2,PGP,PGPUV,PGP3A,PGP3B,PGP2,status)
    implicit none
    REAL(KIND=JPRB), OPTIONAL, INTENT(IN) :: PSPVOR(:, :)
    REAL(KIND=JPRB), OPTIONAL, INTENT(IN) :: PSPDIV(:, :)
    REAL(KIND=JPRB), OPTIONAL, INTENT(IN) :: PSPSCALAR(:, :)
    REAL(KIND=JPRB), OPTIONAL, INTENT(IN) :: PSPSC3A(:, :, :)
    REAL(KIND=JPRB), OPTIONAL, INTENT(IN) :: PSPSC3B(:, :, :)
    REAL(KIND=JPRB), OPTIONAL, INTENT(IN) :: PSPSC2(:, :)
    LOGICAL, OPTIONAL, INTENT(IN) :: LDSCDERS
    LOGICAL, OPTIONAL, INTENT(IN) :: LDVORGP
    LOGICAL, OPTIONAL, INTENT(IN) :: LDDIVGP
    LOGICAL, OPTIONAL, INTENT(IN) :: LDUVDER
    LOGICAL, OPTIONAL, INTENT(IN) :: LDLATLON
    INTEGER(KIND=JPIM), OPTIONAL, INTENT(IN) :: KPROMA
    INTEGER(KIND=JPIM), OPTIONAL, INTENT(IN) :: KVSETUV(:)
    INTEGER(KIND=JPIM), OPTIONAL, INTENT(IN) :: KVSETSC(:)
    INTEGER(KIND=JPIM), OPTIONAL, INTENT(IN) :: KVSETSC3A(:)
    INTEGER(KIND=JPIM), OPTIONAL, INTENT(IN) :: KVSETSC3B(:)
    INTEGER(KIND=JPIM), OPTIONAL, INTENT(IN) :: KVSETSC2(:)
    INTEGER(KIND=JPIM), OPTIONAL, INTENT(IN) :: KRESOL
    EXTERNAL FSPGL_PROC
    OPTIONAL FSPGL_PROC
    REAL(KIND=JPRB), OPTIONAL, INTENT(INOUT) :: PGP(:, :, :)
    REAL(KIND=JPRB), OPTIONAL, INTENT(INOUT) :: PGPUV(:, :, :, :)
    REAL(KIND=JPRB), OPTIONAL, INTENT(INOUT) :: PGP3A(:, :, :, :)
    REAL(KIND=JPRB), OPTIONAL, INTENT(INOUT) :: PGP3B(:, :, :, :)
    REAL(KIND=JPRB), OPTIONAL, INTENT(INOUT) :: PGP2(:, :, :)
    integer(int32), intent(out) :: status
    status = 2
    if (.not. present(KRESOL)) return
    if (KRESOL < 1) return
    if (present(KPROMA)) then
      if (KPROMA < 1) return
    end if
    if (present(FSPGL_PROC)) return
    if (.not. transform_environment_ready()) return
call INV_TRANS(PSPVOR=PSPVOR,PSPDIV=PSPDIV,PSPSCALAR=PSPSCALAR,PSPSC3A=PSPSC3A,PSPSC3B=PSPSC3B,PSPSC2=PSPSC2,FSPGL_PROC=FSPGL_PROC,LDSCDERS=LDSCDERS,LDVORGP=LDVORGP,LDDIVGP=LDDIVGP,LDUVDER=LDUVDER,LDLATLON=LDLATLON,KPROMA=KPROMA,KVSETUV=KVSETUV,KVSETSC=KVSETSC,KRESOL=KRESOL,KVSETSC3A=KVSETSC3A,KVSETSC3B=KVSETSC3B,KVSETSC2=KVSETSC2,PGP=PGP,PGPUV=PGPUV,PGP3A=PGP3A,PGP3B=PGP3B,PGP2=PGP2)
!$omp atomic update
    completed(1) = completed(1) + 1_int64
    status = 0
  end subroutine
!> Forward explicitly present arrays to the public transform library.
!! Arrays retain their physical units and source field order. Status2 refuses
!! an absent resolution, invalid block length or unsupported callback before the call.
subroutine direct_transform_service(PSPVOR,PSPDIV,PSPSCALAR,PSPSC3A,PSPSC3B,PSPSC2,LDLATLON,KPROMA,KVSETUV,KVSETSC,KRESOL,KVSETSC3A,KVSETSC3B,KVSETSC2,PGP,PGPUV,PGP3A,PGP3B,PGP2,status)
    implicit none
    REAL(KIND=JPRB), OPTIONAL, INTENT(INOUT) :: PSPVOR(:, :)
    REAL(KIND=JPRB), OPTIONAL, INTENT(INOUT) :: PSPDIV(:, :)
    REAL(KIND=JPRB), OPTIONAL, INTENT(INOUT) :: PSPSCALAR(:, :)
    REAL(KIND=JPRB), OPTIONAL, INTENT(INOUT) :: PSPSC3A(:, :, :)
    REAL(KIND=JPRB), OPTIONAL, INTENT(INOUT) :: PSPSC3B(:, :, :)
    REAL(KIND=JPRB), OPTIONAL, INTENT(INOUT) :: PSPSC2(:, :)
    INTEGER(KIND=JPIM), OPTIONAL, INTENT(IN) :: KPROMA
    INTEGER(KIND=JPIM), OPTIONAL, INTENT(IN) :: KVSETUV(:)
    INTEGER(KIND=JPIM), OPTIONAL, INTENT(IN) :: KVSETSC(:)
    INTEGER(KIND=JPIM), OPTIONAL, INTENT(IN) :: KVSETSC3A(:)
    INTEGER(KIND=JPIM), OPTIONAL, INTENT(IN) :: KVSETSC3B(:)
    INTEGER(KIND=JPIM), OPTIONAL, INTENT(IN) :: KVSETSC2(:)
    INTEGER(KIND=JPIM), OPTIONAL, INTENT(IN) :: KRESOL
    LOGICAL, OPTIONAL, INTENT(IN) :: LDLATLON

    REAL(KIND=JPRB), OPTIONAL, INTENT(IN) :: PGP(:, :, :)
    REAL(KIND=JPRB), OPTIONAL, INTENT(IN) :: PGPUV(:, :, :, :)
    REAL(KIND=JPRB), OPTIONAL, INTENT(IN) :: PGP3A(:, :, :, :)
    REAL(KIND=JPRB), OPTIONAL, INTENT(IN) :: PGP3B(:, :, :, :)
    REAL(KIND=JPRB), OPTIONAL, INTENT(IN) :: PGP2(:, :, :)
    integer(int32), intent(out) :: status
    status = 2
    if (.not. present(KRESOL)) return
    if (KRESOL < 1) return
    if (present(KPROMA)) then
      if (KPROMA < 1) return
    end if
    if (.not. transform_environment_ready()) return
call DIR_TRANS(PSPVOR=PSPVOR,PSPDIV=PSPDIV,PSPSCALAR=PSPSCALAR,PSPSC3A=PSPSC3A,PSPSC3B=PSPSC3B,PSPSC2=PSPSC2,LDLATLON=LDLATLON,KPROMA=KPROMA,KVSETUV=KVSETUV,KVSETSC=KVSETSC,KRESOL=KRESOL,KVSETSC3A=KVSETSC3A,KVSETSC3B=KVSETSC3B,KVSETSC2=KVSETSC2,PGP=PGP,PGPUV=PGPUV,PGP3A=PGP3A,PGP3B=PGP3B,PGP2=PGP2)
!$omp atomic update
    completed(2) = completed(2) + 1_int64
    status = 0
  end subroutine
!> Return only completed source wrapper calls; counters are outside model fields.
  function transform_service_calls() result(value)
    integer(int64) :: value(2)
    value = completed
  end function
end module
